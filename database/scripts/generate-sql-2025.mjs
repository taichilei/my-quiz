
// 生成 INSERT SQL 文件
import fs from 'fs';

const JSON_FILE = '/Users/tai/Projects/my-quiz/database/test/2025招聘笔试.json';
const SQL_FILE = '/Users/tai/Projects/my-quiz/database/test/2025招聘笔试.sql';

const questions = JSON.parse(fs.readFileSync(JSON_FILE, 'utf8'));

let sql = '-- 批量插入 2025招聘笔试真题\n';
sql += '-- Generated by generate-sql-2025.mjs\n\n';

const now = Math.floor(Date.now() / 1);

for (const q of questions) {
  // 对 JSON 字段进行转义
  const options = JSON.stringify(q.options).replace(/'/g, "''");
  const tags = JSON.stringify(q.tags).replace(/'/g, "''");
  const exam = JSON.stringify(q.exam).replace(/'/g, "''");
  const images = JSON.stringify([]).replace(/'/g, "''");
  const content = q.content.replace(/'/g, "''");
  const explanation = (q.explanation || '').replace(/'/g, "''");
  const answer = q.answer.replace(/'/g, "''");

  sql += `INSERT INTO questions (type, content, options, answer, explanation, difficulty, tags, exam, images, created_at, updated_at)
VALUES ('${q.type}', '${content}', '${options}', '${answer}', '${explanation}', ${q.difficulty}, '${tags}', '${exam}', '${images}', ${now}, ${now});\n\n`;
}

fs.writeFileSync(SQL_FILE, sql, 'utf8');
console.log(`SQL 文件已生成: ${SQL_FILE}`);
console.log(`共 ${questions.length} 条 INSERT 语句`);
