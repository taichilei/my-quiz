async function importQuestions() {
  const existingQuestions = await localforage.getItem('questions') || [];
  const merged = [...existingQuestions, ...questions];
  // Remove duplicates by id
  const unique = Array.from(new Map(merged.map(q => [q.id, q])).values());
  await localforage.setItem('questions', unique);
  console.log(`Imported ${questions.length} questions. Total: ${unique.length}`);
}

